"""Export master data from the 拆單系統 workbook into a SQL seed file.

Usage:  python -I tools/export_seed.py <workbook.xlsx> <out.sql>
Reads:  色號, 單價表, 拆單用, 標記, 資料庫 (status / lookups), 五金配件, 廠商資料
Skips:  客戶資料 (contains personal phone numbers; import separately if wanted)
"""
import sys
from openpyxl import load_workbook

src, out = sys.argv[1], sys.argv[2]
wb_f = load_workbook(src, data_only=False)   # formulas
wb_v = load_workbook(src, data_only=True)    # cached values


def q(v):
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)):
        return repr(v)
    s = " ".join(str(v).split())
    if s == "":
        return "NULL"
    return "'" + s.replace("'", "''") + "'"


def txt(v):
    if v is None:
        return None
    if isinstance(v, float) and v.is_integer():
        v = int(v)
    s = " ".join(str(v).split())
    return s or None


lines = ["-- generated by tools/export_seed.py from " + src, "BEGIN;"]

# ---------- 色號 ----------
ws = wb_v["色號"]
codes = {}
for r in range(2, ws.max_row + 1):
    code = txt(ws.cell(r, 1).value)
    if not code:
        continue
    if code in codes:
        continue
    codes[code] = (txt(ws.cell(r, 2).value), txt(ws.cell(r, 3).value), txt(ws.cell(r, 4).value))
for code, (name, vendor, edge) in codes.items():
    lines.append(f"INSERT INTO color_codes(code, board_name, vendor, edge_code) VALUES ({q(code)},{q(name)},{q(vendor)},{q(edge)}) ON CONFLICT DO NOTHING;")
print("color_codes:", len(codes))

# ---------- 單價表 ----------
ws = wb_v["單價表"]
wsf = wb_f["單價表"]
thick = {}
for c in range(5, 14):  # E..M
    t = ws.cell(2, c).value
    if t is not None:
        thick[c] = float(t)
n = 0
seen = set()
for r in range(3, ws.max_row + 1):
    code = txt(ws.cell(r, 2).value)
    if code is None:
        # cached value missing: fall back to the 色號 row this cell references (=色號!A{r-1})
        f = wsf.cell(r, 2).value
        if isinstance(f, str) and f.startswith("=色號!A"):
            code = txt(wb_v["色號"].cell(int(f[len("=色號!A"):]), 1).value)
    if not code or code not in codes:
        continue
    series = txt(ws.cell(r, 1).value)
    if series:
        lines.append(f"UPDATE color_codes SET series={q(series)} WHERE code={q(code)};")
    for c, t in thick.items():
        p = ws.cell(r, c).value
        if isinstance(p, (int, float)) and (code, t) not in seen:
            seen.add((code, t))
            lines.append(f"INSERT INTO price_table(code, thickness, price) VALUES ({q(code)},{t},{p}) ON CONFLICT DO NOTHING;")
            n += 1
print("price rows:", n)

# ---------- 拆單用 ----------
ws = wb_v["拆單用"]
n = 0
for c in range(1, ws.max_column + 1):
    cat = txt(ws.cell(2, c).value)
    if not cat:
        continue
    sort = 0
    for r in range(3, ws.max_row + 1):
        name = txt(ws.cell(r, c).value)
        if not name:
            continue
        sort += 1
        lines.append(f"INSERT INTO part_catalog(category, name, sort) VALUES ({q(cat)},{q(name)},{sort}) ON CONFLICT DO NOTHING;")
        n += 1
print("part_catalog:", n)

# ---------- 標記 ----------
ws = wb_v["標記"]
n = 0
for r in range(2, ws.max_row + 1):
    name = txt(ws.cell(r, 1).value)
    if name:
        lines.append(f"INSERT INTO marks(name, code, number, sort) VALUES ({q(name)},{q(txt(ws.cell(r,2).value))},{q(ws.cell(r,3).value)},{r-1}) ON CONFLICT DO NOTHING;")
        n += 1
    d = txt(ws.cell(r, 7).value)
    if d:
        lines.append(f"INSERT INTO lookup_values(kind, value, sort) VALUES ('設計師',{q(d)},{r-1}) ON CONFLICT DO NOTHING;")
print("marks:", n)

# ---------- 資料庫: 狀態 / 基材 / 板商 / 計價單位 ----------
ws = wb_v["資料庫"]
for r in range(3, ws.max_row + 1):
    s, c = txt(ws.cell(r, 39).value), txt(ws.cell(r, 40).value)  # AM, AN
    if s and c:
        lines.append(f"INSERT INTO status_codes(code, name) VALUES ({q(c)},{q(s)}) ON CONFLICT DO NOTHING;")
for kind, col in [("基材", 11), ("板材廠商", 12), ("計價單位", 27)]:
    seen_v = set()
    for r in range(4, ws.max_row + 1):
        v = txt(ws.cell(r, col).value)
        if v and v not in seen_v:
            seen_v.add(v)
            lines.append(f"INSERT INTO lookup_values(kind, value, sort) VALUES ({q(kind)},{q(v)},{len(seen_v)}) ON CONFLICT DO NOTHING;")

# ---------- 五金配件 ----------
ws = wb_v["五金配件"]
n = 0
for r in range(3, ws.max_row + 1):
    name = txt(ws.cell(r, 4).value)
    if not name:
        continue
    lines.append(
        "INSERT INTO hardware_catalog(vendor, product_name, model, spec, purchase_unit, sales_unit, list_price, note) VALUES ("
        + ",".join(q(txt(ws.cell(r, c).value)) if c != 12 else q(ws.cell(r, c).value) for c in (3, 4, 5, 6, 9, 10, 12, 11))
        + ");"
    )
    n += 1
print("hardware:", n)

# ---------- 廠商資料 ----------
ws = wb_v["廠商資料"]
n = 0
for r in range(3, ws.max_row + 1):
    name = txt(ws.cell(r, 1).value)
    if not name:
        continue
    lines.append(
        "INSERT INTO vendors(name, company_name, tax_id, address, factory_address, phone) VALUES ("
        + ",".join(q(txt(ws.cell(r, c).value)) for c in (1, 3, 4, 5, 6, 7))
        + ") ON CONFLICT DO NOTHING;"
    )
    n += 1
print("vendors:", n)

lines.append("COMMIT;")
open(out, "w", encoding="utf-8").write("\n".join(lines) + "\n")
print("wrote", out, len(lines), "lines")
