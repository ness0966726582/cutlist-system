"""Export pricing / cost reference sheets into 03_seed_extra.sql.

資料庫 AC..AL  → process_prices (五金配件牌價 / 門板加工 / 特殊加工板材)
牌價表(對公司內部) → cabinet_prices
20230916成本分析 → cost_analysis
報價單 / 對帳單 表頭文字 → settings
"""
import sys
from openpyxl import load_workbook

src, out = sys.argv[1], sys.argv[2]
wb = load_workbook(src, data_only=True)


def q(v):
    if v is None or v == "":
        return "NULL"
    if isinstance(v, (int, float)):
        return repr(round(v, 4))
    return "'" + " ".join(str(v).split()).replace("'", "''") + "'"


def t(v):
    if v is None:
        return None
    s = " ".join(str(v).split())
    return s or None


def n(v):
    try:
        return float(v)
    except (TypeError, ValueError):
        return None


L = ["-- generated by tools/export_seed_extra.py", "BEGIN;"]

# ---- process_prices from 資料庫 ----
ws = wb["資料庫"]
sort = 0
for r in range(4, ws.max_row + 1):
    hw, spec, price, unit = t(ws.cell(r, 29).value), t(ws.cell(r, 30).value), n(ws.cell(r, 33).value), t(ws.cell(r, 38).value)
    if hw and price is not None:
        sort += 1
        L.append(f"INSERT INTO process_prices(kind,name,spec,unit,price,sort) VALUES ('五金配件牌價',{q(hw)},{q(spec)},{q(unit)},{price},{sort}) ON CONFLICT (kind,name) DO NOTHING;")
    pn, pu, pp, note = t(ws.cell(r, 31).value), t(ws.cell(r, 32).value), n(ws.cell(r, 34).value), t(ws.cell(r, 36).value)
    if pn:
        sort += 1
        L.append(f"INSERT INTO process_prices(kind,name,spec,unit,price,note,sort) VALUES ('門板加工',{q(pn)},NULL,{q(pu)},{q(pp)},{q(note)},{sort}) ON CONFLICT (kind,name) DO NOTHING;")
    sp, spp = t(ws.cell(r, 36).value), n(ws.cell(r, 37).value)
    if sp and spp is not None and r >= 19:   # AJ 板名 + AK 價 (特殊加工板材)
        sort += 1
        L.append(f"INSERT INTO process_prices(kind,name,spec,unit,price,sort) VALUES ('特殊加工板材',{q(sp)},NULL,'才',{spp},{sort}) ON CONFLICT (kind,name) DO NOTHING;")

# ---- cabinet_prices from 牌價表 ----
ws = wb["牌價表(對公司內部)"]
for r in range(3, 36):
    name = t(ws.cell(r, 2).value)
    if not name:
        continue
    L.append("INSERT INTO cabinet_prices(seq,name,spec,factor,base_price,sell_price,designer_discount,discount2,employee_discount_draw,employee_discount,install_per_cm,sort) VALUES ("
             + ",".join([q(n(ws.cell(r, 1).value)), q(name), q(t(ws.cell(r, 3).value)), q(n(ws.cell(r, 4).value)), q(n(ws.cell(r, 5).value)), q(n(ws.cell(r, 6).value)),
                         q(n(ws.cell(r, 7).value)), q(n(ws.cell(r, 8).value)), q(n(ws.cell(r, 9).value)), q(n(ws.cell(r, 10).value)), q(n(ws.cell(r, 16).value)), str(r - 2)]) + ");")

# ---- cost_analysis from 成本分析 ----
ws = wb["20230916成本分析"]
vendor = series = None
for r in range(7, 47):
    vendor = t(ws.cell(r, 3).value) or vendor
    series = t(ws.cell(r, 4).value) or series
    spec = t(ws.cell(r, 6).value)
    k = n(ws.cell(r, 11).value)
    if not spec or (k is None and n(ws.cell(r, 13).value) in (None, 0)):
        continue
    L.append("INSERT INTO cost_analysis(vendor,series,color_code,spec,base_material,face,list_cost,net_cost,full_cai,usable_cai,edge_m_per_cai,edge_cost,margin,sort) VALUES ("
             + ",".join([q(vendor), q(series), q(t(ws.cell(r, 5).value)), q(spec), q(t(ws.cell(r, 7).value)), q(t(ws.cell(r, 9).value)), q(k), q(n(ws.cell(r, 12).value)),
                         q(n(ws.cell(r, 14).value)), q(n(ws.cell(r, 15).value)), q(n(ws.cell(r, 18).value)), q(n(ws.cell(r, 19).value)), q(n(ws.cell(r, 22).value)), str(r - 6)]) + ");")

# ---- settings (多行文字保留換行；條款每個 ● 一行) ----
import re


def qml(s):
    """多行字串：保留換行，只整理每行內的空白。"""
    lines = [" ".join(x.split()) for x in str(s).replace("\r", "").split("\n")]
    return "'" + "\n".join(l for l in lines if l).replace("'", "''") + "'"


bank_raw = wb["報價單"]["G2"].value or ""
bank = "\n".join(l.strip() for l in str(bank_raw).replace("\r", "").split("\n") if l.strip())
terms_raw = " ".join(str(x) for x in [wb["報價單"]["A33"].value, wb["報價單"]["A34"].value] if x)
terms_raw = re.sub(r"∵[^∵]*∵", "", terms_raw)                       # 有效期限句子改由系統依有效天數印出
terms = "\n".join(("● " + x.strip()) for x in re.split(r"●", terms_raw) if x.strip())
L.append("INSERT INTO settings(key,value) VALUES ('company_name','和旺木作系統櫃有限公司') ON CONFLICT DO NOTHING;")
L.append(f"INSERT INTO settings(key,value) VALUES ('bank_info',{qml(bank)}) ON CONFLICT DO NOTHING;")
L.append(f"INSERT INTO settings(key,value) VALUES ('quote_terms',{qml(terms)}) ON CONFLICT DO NOTHING;")
# 既有資料庫的更新版本 (04_fix_settings.sql 由下方另外輸出)
open(out.replace("03_seed_extra.sql", "04_fix_settings_newlines.sql"), "w", encoding="utf-8").write(
    f"UPDATE settings SET value={qml(bank)} WHERE key='bank_info';\nUPDATE settings SET value={qml(terms)} WHERE key='quote_terms';\n")
L.append("COMMIT;")
open(out, "w", encoding="utf-8").write("\n".join(L) + "\n")
print("lines", len(L))
